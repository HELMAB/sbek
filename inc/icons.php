/**
 * Return a ready-to-output inline SVG icon.
 *
 * Inner markup is trusted/static; caller-supplied attributes are escaped.
 *
 * @param string               $name  Icon name from sbek_icon_paths().
 * @param array<string,scalar> $attrs Extra/override SVG attributes (e.g. width, height, class).
 * @return string SVG markup, or '' if the icon is unknown.
 */
function sbek_icon( string $name, array $attrs = [] ): string {
	$icons = sbek_icon_paths();

	if ( ! isset( $icons[ $name ] ) ) {
		return '';
	}

	$style   = $icons[ $name ][0];
	$inner   = $icons[ $name ][1];
	$viewbox = $icons[ $name ][2] ?? '0 0 24 24';

	$extra_class = isset( $attrs['class'] ) ? ' ' . $attrs['class'] : '';
	unset( $attrs['class'] );

	// Solid brand logos fill; line UI icons stroke.
	$style_attrs = 'solid' === $style
		? [ 'fill' => 'currentColor' ]
		: [
			'fill'            => 'none',
			'stroke'          => 'currentColor',
			'stroke-width'    => 2,
			'stroke-linecap'  => 'round',
			'stroke-linejoin' => 'round',
		];

	$attributes = array_merge(
		[
			'xmlns'       => 'http://www.w3.org/2000/svg',
			'width'       => 20,
			'height'      => 20,
			'viewBox'     => $viewbox,
			'aria-hidden' => 'true',
			'focusable'   => 'false',
		],
		$style_attrs,
		$attrs
	);

	$attributes['class'] = 'sbek-icon sbek-icon-' . $name . $extra_class;

	$out = '<svg';
	foreach ( $attributes as $key => $value ) {
		$out .= ' ' . esc_attr( $key ) . '="' . esc_attr( (string) $value ) . '"';
	}
	$out .= '>' . $inner . '</svg>';

	return $out;
}

