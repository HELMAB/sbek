 * Falls back to the generic "link" icon for unknown platforms.
 *
 * @param string $platform Platform label (e.g. "Facebook", "X", "Tik Tok").
 * @return string Icon name registered in sbek_icon_paths().
 */
function sbek_social_icon_name( string $platform ): string {
	return sbek_social_icon_aliases()[ strtolower( trim( $platform ) ) ] ?? 'link';
}

/**
 * Lower-case platform label => brand icon name (also passed to the Sbek Theme
 * page JS so the row icon updates while typing).
 *
 * @return array<string,string>
 */
function sbek_social_icon_aliases(): array {
	return [
		'facebook'  => 'facebook',
		'fb'        => 'facebook',
		'messenger' => 'facebook',
		'telegram'  => 'telegram',
		'tiktok'    => 'tiktok',
		'tik tok'   => 'tiktok',
		'instagram' => 'instagram',
		'ig'        => 'instagram',
		'insta'     => 'instagram',
		'twitter'   => 'x',
		'x'         => 'x',
		'youtube'   => 'youtube',
		'yt'        => 'youtube',
		'linkedin'  => 'linkedin',
		'whatsapp'  => 'whatsapp',
		'whats app' => 'whatsapp',
	];
}
